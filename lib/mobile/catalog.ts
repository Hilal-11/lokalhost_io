export const KIND_SEGMENT: Record<ItemKind, string> = {
  component: "components",
  screen: "screens",
  block: "blocks",
};

export const KIND_LABEL: Record<ItemKind, string> = {
  component: "Components",
  screen: "Screens",
  block: "Blocks",
};

export function itemHref(item: Pick<MobileItem, "kind" | "slug">) {
  return `/mobile/${KIND_SEGMENT[item.kind]}/${item.slug}`;
}

export function getItem(kind: ItemKind, slug: string) {
  return CATALOG.find((i) => i.kind === kind && i.slug === slug);
}

export function getItemBySlug(slug: string) {
  return CATALOG.find((i) => i.slug === slug);
}

export function itemsOf(kind: ItemKind) {
  return CATALOG.filter((i) => i.kind === kind);
}

export function toSummary(item: MobileItem): MobileItemSummary {
  return {
    slug: item.slug,
    kind: item.kind,
    href: itemHref(item),
    title: item.title,
    description: item.description,
    category: item.category,
    tags: item.tags,
    tier: item.tier,
    badge: item.badge,
    platforms: item.platforms,
    variants: item.variants,
    preview: item.preview,
    featured: item.featured,
    flow: item.flow,
  };
}

export function getSummaries() {
  return CATALOG.map(toSummary);
}

/** Prev / next across the whole library in sidebar order. */
export function getItemNeighbours(item: MobileItem) {
  const order = [...itemsOf("component"), ...itemsOf("screen"), ...itemsOf("block")];
  const i = order.findIndex((x) => x.slug === item.slug && x.kind === item.kind);
  const prev = order[i - 1];
  const next = order[i + 1];
  return {
    previous: prev ? { title: prev.title, href: itemHref(prev), kind: KIND_LABEL[prev.kind] } : undefined,
    next: next ? { title: next.title, href: itemHref(next), kind: KIND_LABEL[next.kind] } : undefined,
  };
}
